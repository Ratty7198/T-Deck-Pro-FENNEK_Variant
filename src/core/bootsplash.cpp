// Output text of size `size`, centred horizontally at y (similar to
// appmgr::drawCentered, duplicated locally here — appmgr.h does not export it).
void drawCentered(Adafruit_GFX& g, int y, const char* utf8, uint8_t size) {
  g.setTextSize(size);
  uint16_t w, h;
  gui::textBounds(g, utf8, &w, &h);
  gui::printAt(g, (EINK_W - (int)w) / 2, y, utf8, size);
}

